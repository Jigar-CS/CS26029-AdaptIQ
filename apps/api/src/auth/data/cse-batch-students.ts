/**
 * Normalizes an Indian name string to clean Title Case.
 * Example: "AGHERA JAY PRAVINBHAI" -> "Aghera Jay Pravinbhai"
 */
export function formatStudentName(rawName: string): string {
  if (!rawName) return '';
  return rawName
    .split(' ')
    .filter(Boolean)
    .map((word) => {
      // Keep initials like "KA." clean
      if (word.endsWith('.')) return word.toUpperCase();
      return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
    })
    .join(' ');
}

/**
 * Searches the preloaded batch list for a matching student.
 * Matches by:
 * 1. Exact Student ID / Enrollment Number (case-insensitive)
 * 2. Student ID embedded inside the email address (e.g. "24cs001@charusat.edu.in", "jay.24cs001@charusat.edu.in")
 * 3. Exact email match if email was already bound
 */
export function findBatchStudent(emailOrId: string): PreloadedStudent | undefined {
  if (!emailOrId) return undefined;
  const cleaned = emailOrId.trim().toUpperCase();
  const prefix = cleaned.split('@')[0];

  // 1. Direct Student ID match on the prefix or input
  const directMatch = CSE_BATCH_STUDENTS.find(
    (s) => s.studentId.toUpperCase() === prefix || s.studentId.toUpperCase() === cleaned,
  );
  if (directMatch) return directMatch;

  // 2. Check if prefix contains studentId (e.g. "24CS001" inside "AGHERA.24CS001")
  const idMatch = CSE_BATCH_STUDENTS.find((s) => {
    const sId = s.studentId.toUpperCase();
    return prefix.includes(sId);
  });
  if (idMatch) return idMatch;

  // 3. Check if email prefix matches student's normalized name components (e.g. "jay.aghera" -> "AGHERA JAY PRAVINBHAI")
  const nameParts = prefix.toLowerCase().split(/[._-]/).filter((p) => p.length >= 3);
  if (nameParts.length >= 2) {
    const nameMatch = CSE_BATCH_STUDENTS.find((s) => {
      const sNameLower = s.name.toLowerCase();
      return nameParts.every((part) => sNameLower.includes(part));
    });
    if (nameMatch) return nameMatch;
  }

  return undefined;
}

/**
 * Determines whether a student belongs to DIV 1 (24CS001 - 24CS065) or DIV 2 (24CS066 and remaining).
 */
export function getBatchStudentDivision(studentId: string): string {
  if (!studentId) return 'DIV 1';
  const upper = studentId.trim().toUpperCase();
  const match = upper.match(/^24CS(\d+)$/);
  if (match) {
    const num = parseInt(match[1], 10);
    return num <= 65 ? 'DIV 1' : 'DIV 2';
  }
  return 'DIV 2';
}
